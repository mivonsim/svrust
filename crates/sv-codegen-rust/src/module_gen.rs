/// Sinyal yang diawasi `@(...)` pada blok `initial`, urut dan tanpa duplikat.
fn sinyal_terawasi(design: &Design) -> Vec<u32> {
    let mut out: Vec<u32> = Vec::new();
    for segments in crate::initial_step::segmen_design(design) {
        for segment in segments {
            for sinyal in crate::initial_step::sinyal_event_control(&segment) {
                if !out.contains(&sinyal) {
                    out.push(sinyal);
                }
            }
        }
    }
    out
}

/// Seluruh sinyal yang nilainya harus disimpan `sample_edge`.
///
/// Gabungan sinyal yang diawasi blok `initial` dan sinyal sensitivitas proses
/// sekuensial dengan event gabungan; keduanya dibandingkan dengan langkah
/// sebelumnya untuk mengenali edge (LRM §9.7).
fn sinyal_disampel(design: &Design) -> Vec<u32> {
    let mut out = sinyal_terawasi(design);
    for process in design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Sequential)
    {
        if process.sensitivity.len() > 1 {
            for item in &process.sensitivity {
                if !out.contains(&item.signal) {
                    out.push(item.signal);
                }
            }
        }
    }
    out
}

/// Sinyal dan sisi edge dari statement `@(...)` di awal sebuah segmen.
fn await_event_control(
    segment: &[sv_ir::process::Statement],
) -> Option<&[sv_ir::process::EventItem]> {
    match segment.first() {
        Some(sv_ir::process::Statement::EventControl { events, .. }) => Some(events.as_slice()),
        _ => None,
    }
}

/// Gabungkan seluruh item event jadi satu kondisi OR (LRM §9.7).
///
/// `@(posedge clk or negedge rst)` memicu bila salah satu edge terjadi.
fn edge_test(events: &[sv_ir::process::EventItem]) -> String {
    if events.is_empty() {
        return "false".to_string();
    }
    events
        .iter()
        .map(edge_test_item)
        .collect::<Vec<String>>()
        .join(" || ")
}

/// Kondisi Rust untuk satu item event.
fn edge_test_item(item: &sv_ir::process::EventItem) -> String {
    use sv_ir::process::EdgeSensitivity;
    let prev = format!("self.edge_prev[{}] & 1", item.signal);
    let now = format!("self.signals[{}].read().to_u64() & 1", item.signal);
    match item.edge {
        EdgeSensitivity::Posedge => format!("{} == 0 && {} == 1", prev, now),
        EdgeSensitivity::Negedge => format!("{} == 1 && {} == 0", prev, now),
        EdgeSensitivity::AnyChange => format!("{} != {}", prev, now),
    }
}

