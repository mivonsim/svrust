/// Tulis method `refresh_monitor_args` dan `run_monitor` untuk `$monitor`.
///
/// Nilai argumen dievaluasi ulang setiap pemancaran; kalau hanya disimpan
/// sekali saat pendaftaran, `$monitor` akan menampilkan nilai basi.
fn write_run_monitor(design: &Design, inner: &Indent, out: &mut String) {
    if !crate::system_task_gen::uses_monitor_flag(design) {
        return;
    }
    let Some(task) = crate::system_task_gen::find_monitor(design) else {
        // Hanya `$monitoron`/`$monitoroff`: format argumen tidak pernah diisi.
        inner.push(out);
        out.push_str("pub fn run_monitor(&mut self) {\n");
        let body = inner.child();
        body.push(out);
        out.push_str("let _ = self.monitor_active;\n");
        inner.push(out);
        out.push_str("}\n\n");
        return;
    };

    inner.push(out);
    out.push_str("fn refresh_monitor_args(&mut self) {\n");
    let body = inner.child();
    body.push(out);
    out.push_str("self.monitor_args = vec![\n");
    crate::system_task_gen::write_monitor_args(&task.args, out, &body);
    // Syarat `$monitor if` dievaluasi ulang tiap pemancaran, sama seperti
    // argumennya, karena bisa bergantung pada sinyal yang berubah (LRM §20.2).
    if let Some(kondisi) = &task.condition {
        body.push(out);
        out.push_str("self.monitor_cond = ");
        crate::expr_gen::write_truthy_pub(kondisi, out, &body);
        out.push_str(";\n");
    }
    inner.push(out);
    out.push_str("}\n\n");

    inner.push(out);
    out.push_str("pub fn run_monitor(&mut self) {\n");
    let body = inner.child();
    body.push(out);
    out.push_str("if self.monitor_active {\n");
    let dalam = body.child();
    dalam.push(out);
    out.push_str("self.refresh_monitor_args();\n");
    // Tanpa syarat, `$monitor` selalu mencetak; dengan syarat, hanya saat
    // syaratnya bernilai benar (LRM §20.2).
    let ada_syarat = task.condition.is_some();
    if ada_syarat {
        dalam.push(out);
        out.push_str("if self.monitor_cond {\n");
    }
    let cetak = dalam.child();
    cetak.push(out);
    // Skala `%t` milik modul yang memuat `$monitor` (LRM §20.4 + §21.8).
    out.push_str(&format!(
        "print!(\"{{}}\", sv_runtime::sv_format_args({:?}, &self.monitor_args, {}));\n",
        crate::system_task_gen::format_monitor(&task.args),
        crate::time_gen::literal_time_scale_dari(task.time_scale)
    ));
    if ada_syarat {
        dalam.push(out);
        out.push_str("}\n");
    }
    body.push(out);
    out.push_str("}\n");
    inner.push(out);
    out.push_str("}\n\n");
}

