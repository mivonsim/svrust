/// Sinyal yang diawasi `@(...)` pada blok `initial`, urut dan tanpa duplikat.
fn sinyal_terawasi(design: &Design) -> Vec<u32> {
    let mut out: Vec<u32> = Vec::new();
    for segments in crate::initial_step::segmen_design(design) {
        for segment in segments {
            for sinyal in crate::initial_step::sinyal_event_control(&segment) {
                if !out.contains(&sinyal) {
                    out.push(sinyal);
                }
            }
        }
    }
    out
}

/// Seluruh sinyal yang nilainya harus disimpan `sample_edge`.
///
/// Gabungan sinyal yang diawasi blok `initial` dan sinyal sensitivitas proses
/// sekuensial dengan event gabungan; keduanya dibandingkan dengan langkah
/// sebelumnya untuk mengenali edge (LRM §9.7).
///
/// BUG: bila ada proses waktu `always #N` (LRM §11.2), SEMUA sinyal sensitivitas
/// proses sekuensial harus ikut disampel — bukan hanya yang sensitivitasnya lebih
/// dari satu. Tanpa itu `edge_prev` tidak pernah diisi untuk clock Tunggal,
/// sehingga `edge_test` membandingkan `0` dengan nilai sekarang dan posedge
/// pertama yang muncul dianggap sedang terjadi (atau tidak pernah terjadi),
/// tergantung nilai awal clock.
fn sinyal_disampel(design: &Design) -> Vec<u32> {
    let mut out = sinyal_terawasi(design);
    let semua_sensitif = crate::time_scan::jumlah_proses_waktu(design) > 0;
    for process in design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Sequential)
    {
        if process.sensitivity.len() > 1 || semua_sensitif {
            for item in &process.sensitivity {
                if !out.contains(&item.signal) {
                    out.push(item.signal);
                }
            }
        }
    }
    out
}

/// Sinyal dan sisi edge dari statement `@(...)` di awal sebuah segmen.
fn await_event_control(
    segment: &[sv_ir::process::Statement],
) -> Option<&[sv_ir::process::EventItem]> {
    match segment.first() {
        Some(sv_ir::process::Statement::EventControl { events, .. }) => Some(events.as_slice()),
        _ => None,
    }
}

/// Gabungkan seluruh item event jadi satu kondisi OR (LRM §9.7).
///
/// `@(posedge clk or negedge rst)` memicu bila salah satu edge terjadi.
fn edge_test(events: &[sv_ir::process::EventItem]) -> String {
    if events.is_empty() {
        return "false".to_string();
    }
    events
        .iter()
        .map(edge_test_item)
        .collect::<Vec<String>>()
        .join(" || ")
}

/// Kondisi Rust untuk satu item event.
fn edge_test_item(item: &sv_ir::process::EventItem) -> String {
    use sv_ir::process::EdgeSensitivity;
    let prev = format!("self.edge_prev[{}] & 1", item.signal);
    let now = format!("self.signals[{}].read().to_u64() & 1", item.signal);
    match item.edge {
        EdgeSensitivity::Posedge => format!("{} == 0 && {} == 1", prev, now),
        EdgeSensitivity::Negedge => format!("{} == 1 && {} == 0", prev, now),
        EdgeSensitivity::AnyChange => format!("{} != {}", prev, now),
    }
}

// LRM §9.7: nilai sekarang dibaca langsung dari sel sinyal, sedangkan nilai
// sebelumnya disimpan oleh `sample_edge`.

/// Nama proses untuk komentar pada segmen langkah waktu.
fn nama_proses(index: usize) -> String {
    format!("initial[{}]", index)
}

/// True bila design punya setidaknya satu proses `initial`.
pub fn has_initial(design: &Design) -> bool {
    design
        .processes
        .iter()
        .any(|p| p.kind == ProcessKind::Initial)
}

fn write_commit_pending(inner: &Indent, out: &mut String) {
    inner.push(out);
    out.push_str("pub fn commit_pending(&mut self) {\n");
    let body = inner.child();
    body.push(out);
    out.push_str("for write in std::mem::take(&mut self.pending) {\n");
    body.child().push(out);
    out.push_str("self.signals[write.target].write_masked(write.value, write.mask);\n");
    body.push(out);
    out.push_str("}\n");
    inner.push(out);
    out.push_str("}\n\n");
}

/// Lebar penyimpanan `Bits<MAX_WIDTH>` untuk seluruh design.
///
/// Hanya melihat lebar variabel **belum cukup**: nilai yang lebih lebar muncul
/// juga dari konstanta dan dari lebar tipe pada ekspresi — `$bits(...)` selalu
/// konstanta 32-bit, dan `typedef logic [127:0] wide_t` menghasilkan cast ke
/// 128 bit walaupun tidak ada satu pun sinyal 128-bit di design. Karena
/// `Bits::set` diam-diam mengabaikan indeks di luar `N`, jadi baik konstanta
/// maupun bit perluasan cast akan hilang tanpa error — dan pemformat `%h`
/// meng-zero-pad hasilnya, jadi nilainya terlihat "benar" tapi salah.
///
/// Semua lebar yang muncul di ekspresi ikut dipetakan supaya tidak ada nilai
/// yang terpotong.
fn max_width(design: &Design) -> u32 {
    let mut lebar = design
        .variables
        .iter()
        .map(|v| v.data_type.width)
        .max()
        .unwrap_or(1)
        .max(1);

    // `$time` bertipe 64-bit; kalau design hanya punya sinyal sempit,
    // nilainya akan terpangkas oleh masker `Bits<MAX_WIDTH>`.
    if crate::time_scan::has_time(design) {
        lebar = lebar.max(64);
    }

    let mut ekspresi = Vec::new();
    for process in &design.processes {
        kumpulkan_list(&process.body, &mut ekspresi);
    }
    for expr in &ekspresi {
        lebar = lebar.max(max_width_expr(expr));
    }
    // Lebar argumen pada pemanggilan system task juga penting: `$display("%h",
    // word_t'(x))` menyimpan lebar logis tipe pada `FormatArg`, dan
    // `to_hex_str` membaca sebanyak itu digit — lebih sedikit bit daripada
    // yang diminta berarti digit atas tercetak sebagai `x`/`z` atau hilang.
    for process in &design.processes {
        for stmt in &process.body {
            kumpulkan_argumen(stmt, &mut lebar);
        }
    }
    lebar
}

/// Perbarui `lebar` dengan lebar tipe argumen pada system task.
///
/// Berbeda dari ekspresi biasa, konstanta di sini **tidak** boleh dipangkas ke
/// bit significant: `$display("%h", 32'hDEADBEEF)` meminta 8 digit heksa
/// melalui `FormatArg::width`, dan hanya 4 bit yang bernilai. Memangkas ke 4
/// membuat 4 digit atas tercetak `0000` — benar secara nilai, salah secara
/// tampilan.
fn kumpulkan_argumen(stmt: &Statement, lebar: &mut u32) {
    match stmt {
        Statement::SystemTask {
            args, condition, ..
        } => {
            for arg in args {
                if let sv_ir::expr::SystemArg::Value(expr) = arg {
                    *lebar = (*lebar).max(lebar_logis_penuh(expr));
                }
            }
            if let Some(cond) = condition {
                *lebar = (*lebar).max(lebar_logis_penuh(cond));
            }
        }
        Statement::Assign { assignment, .. } => {
            *lebar = (*lebar).max(lebar_logis_penuh(&assignment.value));
        }
        Statement::If {
            condition,
            then_branch,
            else_branch,
            ..
        } => {
            *lebar = (*lebar).max(lebar_logis_penuh(condition));
            for s in then_branch.iter().chain(else_branch.iter()) {
                kumpulkan_argumen(s, lebar);
            }
        }
        Statement::Case { selector, arms, .. } => {
            *lebar = (*lebar).max(lebar_logis_penuh(selector));
            for arm in arms {
                for label in &arm.labels {
                    *lebar = (*lebar).max(lebar_logis_penuh(label));
                }
                for s in &arm.body {
                    kumpulkan_argumen(s, lebar);
                }
            }
        }
        Statement::For {
            init,
            condition,
            step,
            body,
            ..
        } => {
            *lebar = (*lebar)
                .max(lebar_logis_penuh(&init.value))
                .max(lebar_logis_penuh(condition))
                .max(lebar_logis_penuh(&step.value));
            for s in body {
                kumpulkan_argumen(s, lebar);
            }
        }
        Statement::Repeat { count, body, .. } => {
            *lebar = (*lebar).max(lebar_logis_penuh(count));
            for s in body {
                kumpulkan_argumen(s, lebar);
            }
        }
        Statement::While {
            condition, body, ..
        } => {
            *lebar = (*lebar).max(lebar_logis_penuh(condition));
            for s in body {
                kumpulkan_argumen(s, lebar);
            }
        }
        Statement::Block { body, .. } | Statement::EventControl { body, .. } => {
            for s in body {
                kumpulkan_argumen(s, lebar);
            }
        }
        Statement::Delay { amount, body, .. } => {
            *lebar = (*lebar).max(lebar_logis_penuh(amount));
            kumpulkan_argumen(body, lebar);
        }
        Statement::Noop { .. } => {}
    }
}

/// Lebar logis penuh satu ekspresi: konstanta memakai lebar tipenya, bukan
/// hanya bit yang significance-nya.
fn lebar_logis_penuh(expr: &Expr) -> u32 {
    expr.data_type().width
}

/// Lebar terbesar yang muncul pada satu ekspresi beserta seluruh anaknya.
fn max_width_expr(expr: &Expr) -> u32 {
    // Konstanta dikecualikan dari lebar tipenya: LRM §5.7.1 memberi literal
    // desimal polos lebar 32, tapi `0` hanya butuh satu digit. Mengambil
    // `data_type().width` untuk konstanta akan memaksa `MAX_WIDTH` jadi 32
    // hanya karena ada `== 0` di design yang sinyalnya 8 bit.
    let lebar_tipe = match expr {
        Expr::Const { .. } => 0,
        other => other.data_type().width,
    };
    lebar_tipe.max(match expr {
        Expr::Bin { lhs, rhs, .. } => max_width_expr(lhs).max(max_width_expr(rhs)),
        Expr::Un { operand, .. } | Expr::Cast { operand, .. } => max_width_expr(operand),
        // `Select`/`Index` membaca base pada posisi bit yang ditentukan lebarnya,
        // jadi lebar logis base WAJIB ikut dihitung. Kalau tidak, `MAX_WIDTH`
        // bisa lebih kecil dari lebar base — helper runtime lalu memakai
        // `Bits::<MAX_WIDTH>` dan indeks di atas `MAX_WIDTH` membaca bit yang
        // tidak ada (`Logic::X`) padahal nilainya ada di sinyal.
        Expr::Select { base, .. } => max_width_expr(base).max(base.data_type().width),
        Expr::Ternary {
            condition,
            when_true,
            when_false,
            ..
        } => max_width_expr(condition)
            .max(max_width_expr(when_true))
            .max(max_width_expr(when_false)),
        Expr::Concat { items, .. } => items.iter().map(max_width_expr).max().unwrap_or(0),
        Expr::Replicate { value, .. } => max_width_expr(value),
        Expr::Index { base, index, .. } => max_width_expr(base)
            .max(max_width_expr(index))
            .max(base.data_type().width),
        Expr::SignalRef { .. } | Expr::SimTime { .. } => 0,
        // Konstanta hanya butuh ruang sampai bit tertinggi yang benar-benar
        // bisa bernilai — bukan sepanjang lebar tipenya. LRM §5.7.1 memberi
        // literal desimal polos lebar 32, tapi `0` tetap muat di 1 bit; memaksa
        // `MAX_WIDTH` jadi 32 hanya karena ada `== 0` akan membuat design 8-bit
        // memakai penyimpanan 32-bit tanpa alasan.
        //
        // `X`/`Z` ikut dihitung karena keduanya disimpan sebagai digit, bukan
        // sebagai nilai.
        Expr::Const {
            value,
            unknown_mask,
            zmask,
            ..
        } => significant_bits(*value)
            .max(significant_bits(*unknown_mask))
            .max(significant_bits(*zmask)),
    })
}

/// Bit tertinggi yang mungkin bernilai satu, dihitung satu-based.
///
/// Nol menghasilkan 1 karena vektor harus tetap bisa menyimpan satu digit.
fn significant_bits(value: u64) -> u32 {
    (64 - value.leading_zeros()).max(1)
}

/// Kumpulkan seluruh ekspresi yang muncul pada satu statement.
fn kumpulkan_stmt(stmt: &Statement, out: &mut Vec<Expr>) {
    match stmt {
        Statement::Assign { assignment, .. } => {
            out.push(assignment.value.clone());
        }
        Statement::Case { selector, arms, .. } => {
            out.push(selector.clone());
            for arm in arms {
                for label in &arm.labels {
                    out.push(label.clone());
                }
                kumpulkan_list(&arm.body, out);
            }
        }
        Statement::If {
            condition,
            then_branch,
            else_branch,
            ..
        } => {
            out.push(condition.clone());
            kumpulkan_list(then_branch, out);
            kumpulkan_list(else_branch, out);
        }
        Statement::For {
            init,
            condition,
            step,
            body,
            ..
        } => {
            // `init` dan `step` adalah `Assignment`, jadi ekspresinya diambil
            // lewat `.value`.
            out.push(init.value.clone());
            out.push(condition.clone());
            out.push(step.value.clone());
            kumpulkan_list(body, out);
        }
        Statement::Repeat { count, body, .. } => {
            out.push(count.clone());
            kumpulkan_list(body, out);
        }
        Statement::While {
            condition, body, ..
        } => {
            out.push(condition.clone());
            kumpulkan_list(body, out);
        }
        Statement::SystemTask {
            args, condition, ..
        } => {
            for arg in args {
                if let sv_ir::expr::SystemArg::Value(expr) = arg {
                    out.push(expr.clone());
                }
            }
            if let Some(cond) = condition {
                out.push(cond.clone());
            }
        }
        Statement::Block { body, .. } | Statement::EventControl { body, .. } => {
            kumpulkan_list(body, out);
        }
        Statement::Delay { amount, body, .. } => {
            out.push(amount.clone());
            kumpulkan_stmt(body, out);
        }
        Statement::Noop { .. } => {}
    }
}

fn kumpulkan_list(body: &[Statement], out: &mut Vec<Expr>) {
    for stmt in body {
        kumpulkan_stmt(stmt, out);
    }
}

pub fn to_struct_name(name: &str) -> String {
    let mut out = String::new();
    let mut capitalize = true;
    for ch in name.chars() {
        if ch == '_' || ch == '.' {
            capitalize = true;
        } else if capitalize {
            out.extend(ch.to_uppercase());
            capitalize = false;
        } else {
            out.push(ch);
        }
    }
    out
}

