// Tanggung jawab: generate struct Rust untuk satu design module.
use crate::indent::Indent;
use crate::stmt_gen::write_statements;
use sv_ir::expr::Expr;
use sv_ir::process::{ProcessKind, Statement};
use sv_ir::Design;

const HEADER: &str = "// Generated by sv-codegen-rust. Jangan edit manual.\n";

/// Generate satu file Rust untuk design.
pub fn generate_module(design: &Design) -> String {
    let mut out = String::new();
    let indent = Indent::new();
    let struct_name = to_struct_name(&design.name);
    let max_width = max_width(design);

    out.push_str(HEADER);
    out.push_str(imports());
    out.push_str(&format!(
        "/// Lebar maksimum sinyal pada design `{}`.\n",
        design.name
    ));
    out.push_str(&format!("pub const MAX_WIDTH: usize = {};\n\n", max_width));
    // Field `sensitivity` dipakai scheduler (milestone event queue) dan
    // `initial_pc` hanya dibaca oleh varian driver bertahap; keduanya boleh
    // tidak terbaca pada driver biasa.
    out.push_str("#[allow(dead_code)]\n");
    out.push_str(&format!("pub struct {0} {{\n", struct_name));
    let field_indent = indent.child();
    field_indent.push(&mut out);
    out.push_str("signals: Vec<SignalCell<MAX_WIDTH>>,\n");
    field_indent.push(&mut out);
    out.push_str("pending: Vec<PendingWrite<MAX_WIDTH>>,\n");
    field_indent.push(&mut out);
    out.push_str("sensitivity: Vec<Vec<usize>>,\n");
    // Flag `$finish` dibutuhkan bila ada blok `initial` ATAU ada proses
    // sekuensial/combinational yang memanggil `$finish`. Gate hanya pada
    // `has_initial` membuat `$finish` di dalam `always_ff` pada design tanpa
    // `initial` tidak punya field untuk ditugaskan.
    let perlu_finish = has_initial(design) || crate::system_task_gen::has_finish(design);
    if perlu_finish {
        field_indent.push(&mut out);
        out.push_str("finished: bool,\n");
    }
    if has_initial(design) {
        // LRM §15.2: tiap proses `initial` punya penunjuk segmen sendiri.
        // Pointer hanya maju setelah segmen selesai, sehingga segmen yang
        // menunggu `@(posedge clk)` boleh dicoba lagi pada langkah berikutnya.
        field_indent.push(&mut out);
        out.push_str("initial_pc: Vec<usize>,\n");
        // LRM §4.4: tiap proses punya waktu bangun sendiri. Satu jam global
        // membuat proses yang tertinggal ikut bergeser mengikuti proses lain.
        field_indent.push(&mut out);
        out.push_str("initial_time: Vec<SimTime>,\n");
    }
    // Nilai sinyal yang diawasi event control pada langkah sebelumnya,
    // dipakai untuk mengenali posedge/negedge (LRM §9.7).
    if perlu_edge_prev(design) {
        field_indent.push(&mut out);
        out.push_str("edge_prev: Vec<u64>,\n");
    }
    // Waktu simulasi dibutuhkan oleh `#delay`, `$time`, DAN `eval_initial` —
    // driver membandingkan titik waktu antar proses pada setiap langkah, jadi
    // field ini wajib ada begitu ada blok `initial` meski desainnya tanpa
    // delay sama sekali. Versi lama hanya memunculkannya bila `has_time`, dan
    // kode hasil generate gagal dengan `no field time_now`.
    //
    // Proses waktu (`always #N`) juga menulisi `time_now`, jadi ikut menghitung
    // sebagai pemicu field ini.
    if crate::time_scan::has_time(design)
        || has_initial(design)
        || crate::time_scan::jumlah_proses_waktu(design) > 0
    {
        field_indent.push(&mut out);
        out.push_str("time_now: SimTime,\n");
    }
    // LRM §9.2.1: tiap proses `always #N` punya waktu bangun sendiri; dua
    // proses `#5` harus keduanya menambah 5 dari waktu yang sama.
    //
    // BUG: field `timed_maks` lama tidak pernah dipakai untuk apa pun yang
    // berarti — `eval_timed` sudah memakai variabel lokal `__maks` sendiri,
    // jadi field itu hanya menambah state yang tidak terpakai.
    if crate::time_scan::jumlah_proses_waktu(design) > 0 {
        field_indent.push(&mut out);
        out.push_str("timed_time: Vec<SimTime>,\n");
    }
    // State `$monitor` hanya perlu ada bila design memakainya.
    if crate::system_task_gen::uses_monitor_flag(design) {
        field_indent.push(&mut out);
        out.push_str("monitor_fmt: &'static str,\n");
        field_indent.push(&mut out);
        out.push_str("monitor_args: Vec<sv_runtime::FormatArg<MAX_WIDTH>>,\n");
        field_indent.push(&mut out);
        out.push_str("monitor_active: bool,\n");
        // LRM §20.2: `$monitor if (kondisi)` menyimpan hasil syarat saat ini.
        if crate::system_task_gen::monitor_condition(design).is_some() {
            field_indent.push(&mut out);
            out.push_str("monitor_cond: bool,\n");
        }
    }
    // LRM §20.3: `$strobe` perlu antrean panggilan sampai akhir timestep.
    if crate::system_task_gen::has_strobe(design) {
        field_indent.push(&mut out);
        out.push_str(
            "// Skala `%t` ikut dibawa: milik modul pemanggil, bukan modul top (LRM §21.8).\n\
             strobe_pending: Vec<(&'static str, sv_runtime::TimeScale, \
             Vec<sv_runtime::FormatArg<MAX_WIDTH>>)>,\n",
        );
    }
    // LRM §23.2: driver membaca dua field ini setelah `initial` t=0 jalan
    // untuk memutuskan apakah VCD perlu ditulis.
    if crate::system_task_gen::has_dumpvars(design) {
        field_indent.push(&mut out);
        out.push_str("dump_on: bool,\n");
        field_indent.push(&mut out);
        out.push_str("dump_path: &'static str,\n");
    }
    indent.push(&mut out);
    out.push_str("}\n\n");

    out.push_str(&format!("impl {0} {{\n", struct_name));
    let inner = indent.child();

    write_new(design, &struct_name, &inner, &mut out);
    write_accessors(design, &inner, &mut out);
    write_eval_comb(design, &inner, &mut out);
    write_eval_timed(design, &inner, &mut out);
    write_eval_seq(design, &inner, &mut out);
    write_sample_edge(design, &inner, &mut out);
    write_eval_initial(design, &inner, &mut out);
    write_is_finished(design, &inner, &mut out);
    write_time_now(design, &inner, &mut out);
    write_snapshot(&inner, &mut out);
    write_run_monitor(design, &inner, &mut out);
    write_run_strobe(design, &inner, &mut out);
    write_dump_accessors(design, &inner, &mut out);
    write_commit_pending(&inner, &mut out);

    inner.push(&mut out);
    out.push_str("}\n");
    out
}

/// Import runtime untuk satu design.
///
/// Path ditulis absolut (`::sv_runtime`) karena design dibungkus `mod <nama>`
/// dan modul SV boleh bernama apa saja — termasuk `sv_runtime`, yang kalau
/// tidak akan memblokir crate aslinya dan membuat `use` berubah jadi
/// `struct import is private`.
fn imports() -> &'static str {
    "use ::sv_runtime::Bits;\n\
     use ::sv_runtime::Logic;\n\
     use ::sv_runtime::PendingWrite;\n\
     use ::sv_runtime::SignalCell;\n\
     use ::sv_runtime::SimTime;\n\n"
}

fn write_new(design: &Design, struct_name: &str, inner: &Indent, out: &mut String) {
    let ada_initial = has_initial(design);
    let perlu_finish = ada_initial || crate::system_task_gen::has_finish(design);
    let ada_waktu = crate::time_scan::has_time(design) || ada_initial;
    inner.push(out);
    out.push_str("pub fn new() -> Self {\n");
    let body = inner.child();
    body.push(out);
    out.push_str(&format!("let signal_count = {};\n", design.variables.len()));
    body.push(out);
    if design.variables.iter().any(|v| v.initial.is_some()) {
        out.push_str("let mut design = Self {\n");
    } else {
        out.push_str("Self {\n");
    }
    let fields = body.child();
    fields.push(out);
    // LRM §4.3.1: nilai awal variabel adalah `x`, bukan `0`. Memulai dari nol
    // membuat variabel yang belum pernah ditulis terbaca sebagai angka pasti,
    // padahal nilainya belum diketahui — dan seluruh logika 4-state berikutnya
    // jadi salah. Lebar logis sinyal tidak dipakai di sini: seluruh vektor
    // penyimpanan diisi `x`, termasuk bit di atas lebar logis yang tidak pernah
    // boleh dibaca.
    out.push_str(
        "signals: (0..signal_count).map(|_| SignalCell::new(Bits::all(Logic::X))).collect(),\n",
    );
    fields.push(out);
    out.push_str("pending: Vec::new(),\n");
    fields.push(out);
    out.push_str("sensitivity: vec![\n");
    for process in &design.processes {
        let list: Vec<String> = process
            .sensitivity
            .iter()
            .map(|item| item.signal.to_string())
            .collect();
        fields.push(out);
        out.push_str(&format!("{}vec![{}],\n", " ".repeat(8), list.join(", ")));
    }
    fields.push(out);
    out.push_str("    ],\n");
    if perlu_finish {
        fields.push(out);
        out.push_str("finished: false,\n");
    }
    if ada_initial {
        fields.push(out);
        out.push_str(&format!(
            "initial_pc: vec![0; {}],\n",
            crate::initial_step::segmen_design(design).len()
        ));
        fields.push(out);
        out.push_str(&format!(
            "initial_time: vec![SimTime::ZERO; {}],\n",
            crate::initial_step::segmen_design(design).len()
        ));
    }
    if perlu_edge_prev(design) {
        fields.push(out);
        out.push_str("edge_prev: vec![0; signal_count],\n");
    }
    if ada_waktu {
        fields.push(out);
        out.push_str("time_now: SimTime::ZERO,\n");
    }
    if crate::time_scan::jumlah_proses_waktu(design) > 0 {
        fields.push(out);
        out.push_str(&format!(
            "timed_time: vec![SimTime::ZERO; {}],\n",
            crate::time_scan::jumlah_proses_waktu(design)
        ));
    }
    if crate::system_task_gen::uses_monitor_flag(design) {
        fields.push(out);
        out.push_str("monitor_fmt: \"\",\n");
        fields.push(out);
        out.push_str("monitor_args: Vec::new(),\n");
        fields.push(out);
        out.push_str("monitor_active: false,\n");
        if crate::system_task_gen::monitor_condition(design).is_some() {
            fields.push(out);
            out.push_str("monitor_cond: false,\n");
        }
    }
    if crate::system_task_gen::has_strobe(design) {
        fields.push(out);
        out.push_str("strobe_pending: Vec::new(),\n");
    }
    if crate::system_task_gen::has_dumpvars(design) {
        fields.push(out);
        out.push_str("dump_on: false,\n");
        fields.push(out);
        out.push_str("dump_path: \"\",\n");
    }
    if design.variables.iter().any(|v| v.initial.is_some()) {
        out.push_str("};\n");
        body.push(out);
        out.push_str("design.init_values();\n");
        body.push(out);
        out.push_str("design\n");
    } else {
        body.push(out);
        out.push_str("}\n");
    }
    inner.push(out);
    out.push_str("}\n\n");
    let _ = struct_name;

    // Nilai awal waktu nol ditulis lewat method terpisah supaya ekspresi
    // inisialisasi boleh membaca sinyal lain lewat `self.signals[..]`.
    if design.variables.iter().any(|v| v.initial.is_some()) {
        inner.push(out);
        out.push_str("fn init_values(&mut self) {\n");
        let init_body = inner.child();
        init_body.push(out);
        for var in &design.variables {
            if let Some(expr) = &var.initial {
                out.push_str(&format!("self.signals[{}] = ", var.signal_id));
                let mut kode = String::new();
                let eks_indent = Indent::new();
                crate::expr_gen::write_expr(expr, &mut kode, &eks_indent);
                out.push_str("SignalCell::new(");
                out.push_str(&kode);
                out.push_str(");\n");
            }
        }
        inner.push(out);
        out.push_str("}\n\n");
    }
}

fn write_accessors(design: &Design, inner: &Indent, out: &mut String) {
    for var in &design.variables {
        let width = var.data_type.width;
        let field = var.name.to_lowercase();

        inner.push(out);
        out.push_str(&format!("pub fn {}(&self) -> Bits<{}> {{\n", field, width));
        inner.child().push(out);
        out.push_str(&format!(
            "self.signals[{}].read().resize::<{}>()\n",
            var.signal_id, width
        ));
        inner.push(out);
        out.push_str("}\n\n");

        inner.push(out);
        out.push_str(&format!(
            "pub fn set_{}(&mut self, value: Bits<{}>) {{\n",
            field, width
        ));
        inner.child().push(out);
        out.push_str(&format!(
            "self.signals[{}].write(value.widen::<MAX_WIDTH>());\n",
            var.signal_id
        ));
        inner.push(out);
        out.push_str("}\n\n");
    }
}

fn write_eval_comb(design: &Design, inner: &Indent, out: &mut String) {
    let combinational: Vec<_> = design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Combinational)
        .collect();
    inner.push(out);
    out.push_str("pub fn eval_comb(&mut self) {\n");
    let body = inner.child();
    for process in &combinational {
        body.push(out);
        out.push_str(&format!("// {}\n", process.name));
        // LRM §20.3: setelah `$finish`, statement berikutnya tidak jalan lagi.
        // Penjaga hanya 필요 kalau design memang punya `$finish`; tanpa itu
        // field `finished` tidak dibangkitkan dan rujukan akan gagal compile.
        write_statements(&process.body, out, &body);
    }
    inner.push(out);
    out.push_str("}\n\n");
}

fn write_eval_timed(design: &Design, inner: &Indent, out: &mut String) {
    let timed: Vec<_> = design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Timed)
        .collect();
    if timed.is_empty() {
        return;
    }
    // LRM §4.4 + §11.2: tiap proses waktu punya jam bangun sendiri, dan simulasi
    // berakhir pada event BERIKUTNYA — bukan pada satu iterasi per proses.
    //
    // BUG: versi lama menjalankan tiap proses tepat SEKALI per pemanggilan
    // driver. Dengan dua proses waktu `#5` dan `#3`, keduanya maju satu periode
    // per langkah: pada t=30 proses `#3` hanya berayun 6 kali (harus 10) dan
    // proses `#5` 6 kali (benar), jadi hasil testbench salah diam-diam.
    //
    // Perbaikan: satu pemanggilan，直到 waktu bangun TERCEPAT dari seluruh
    // proses. Proses yang periodenya lebih pendek mengulang beberapa kali
    // sampai waktunya mengejar, karena LRM §4.4 menganggap keduanya berjalan
    // pada jam simulasi yang sama.
    //
    // Periode harus konstanta agar batas loop bisa ditulis sebagai konstanta;
    // bila ada yang runtime, jatuh ke satu-iterasi-per-pemanggilan.
    let periode = crate::wake_plan::periode_waktu(design).filter(|p| !p.is_empty());

    inner.push(out);
    out.push_str("pub fn eval_timed(&mut self) {\n");
    let arm = inner.child();
    match periode {
        Some(periode) => {
            // Satu iterasi = satu event waktu: majukan jam ke waktu bangun
            // tercepat, lalu jalankan setiap proses yang waktunya sudah tiba.
            //
            // `__t` dideklarasikan DI LUAR loop supaya masih hidup setelah loop
            // selesai — deklarasinya di dalam membuat `self.time_now = __t`
            // gagal dikompilasi dengan `cannot find value __t in this scope`.
            arm.push(out);
            out.push_str(&format!("let __t = {};\n", kode_min_periode(&periode)));
            arm.push(out);
            out.push_str("loop {\n");
            let dalam = arm.child();
            // Pemisah `&&` ditulis SEBELUM tiap suku ke-2, bukan sesudahnya:
            // menempelkannya sesudah membuat dua perbandingan tersambung
            // (`a >= __tb >= __t`), yang ditolak rustc dengan
            // `comparison operators cannot be chained`.
            let syarat: Vec<String> = (0..periode.len())
                .map(|index| format!("self.timed_time[{index}] >= __t"))
                .collect();
            dalam.push(out);
            out.push_str(&format!("let __semua_sampai = {};\n", syarat.join(" && ")));
            dalam.push(out);
            out.push_str("if __semua_sampai { break; }\n");
            for (index, process) in timed.iter().enumerate() {
                dalam.push(out);
                out.push_str(&format!("// {} (proses {index})\n", process.name));
                dalam.push(out);
                out.push_str(&format!("if self.timed_time[{index}] < __t {{\n"));
                let lengan = dalam.child();
                lengan.push(out);
                out.push_str(&format!("self.time_now = self.timed_time[{index}];\n"));
                write_statements(&process.body, out, &lengan.child());
                lengan.push(out);
                out.push_str(&format!("self.timed_time[{index}] = self.time_now;\n"));
                lengan.push(out);
                out.push_str("}\n");
            }
            arm.push(out);
            out.push_str("}\n");
            // Jam desain berada pada event yang baru saja diproses; proses
            // yang tertinggal tidak boleh menarik mundur.
            arm.push(out);
            out.push_str("self.time_now = __t.max(self.time_now);\n");
        }
        None => {
            arm.push(out);
            out.push_str("let mut __maks = self.time_now;\n");
            for (index, process) in timed.iter().enumerate() {
                arm.push(out);
                out.push_str(&format!("// {} (proses {index})\n", process.name));
                // Tiap proses berangkat dari waktu bangun sendiri (LRM §4.4).
                arm.push(out);
                out.push_str(&format!("self.time_now = self.timed_time[{index}];\n"));
                write_statements(&process.body, out, &arm.child());
                arm.push(out);
                out.push_str(&format!("self.timed_time[{index}] = self.time_now;\n"));
                arm.push(out);
                out.push_str("if self.time_now > __maks { __maks = self.time_now; }\n");
            }
            arm.push(out);
            out.push_str("self.time_now = __maks;\n");
        }
    }
    inner.push(out);
    out.push_str("}\n\n");
}

/// Kode Rust untuk `min(timed_time[0] + p0, timed_time[1] + p1, ...)`.
///
/// Periode ditulis sebagai konstanta femtosecond supaya batas loop
/// `eval_timed` bisa ditentukan compiler dan tidak membaca sinyal.
fn kode_min_periode(periode: &[u64]) -> String {
    let bagian: Vec<String> = periode
        .iter()
        .enumerate()
        .map(|(index, periode)| {
            format!(
                "self.timed_time[{index}].saturating_add(sv_runtime::SimTime::from_femtos({periode}))"
            )
        })
        .collect();
    // Setiap `min` membungkus seluruh argumennya, jadi kurung buka harus ikut
    // bertambah seiring jumlah proses — tidak cukup menempelkan `)` sejumlah
    // proses di akhir (hasilnya kurung berlebih dan kode gagal dikompilasi).
    let mut kode = bagian[0].clone();
    for bagian in &bagian[1..] {
        kode = format!("{kode}.min({bagian})");
    }
    kode
}

fn write_eval_seq(design: &Design, inner: &Indent, out: &mut String) {
    let sequential: Vec<_> = design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Sequential)
        .collect();

    // LRM §9.7 + §11.2: ketika clock digerakkan proses waktu (`always #N`),
    // proses sekuensial HANYA boleh jalan pada edge NYATA. Syarat lama
    // `clock == {id}` benar setiap langkah driver, jadi `always_ff @(posedge
    // clk)` ikut jalan pada SETIAP langkah — termasuk saat `clk` tetap 0 di
    // antara dua toggle. Register bergeser jauh lebih cepat dari stimulus,
    // dan tidak ada pesan apa pun.
    //
    // BUG: `clock == {id}` adalah perbandingan id sinyal dengan argumen
    // driver yang juga id sinyal itu, jadi nilainya `true` secara permanen —
    // bukan(edge). Perbandingan edge nyata sudah tersedia lewat `edge_test`,
    // tapi hanya dipakai untuk sensitivitas gabungan, sehingga clock yang
    // digerakkan `always #N` tidak pernah terpakai.
    let edge_nyata = crate::time_scan::jumlah_proses_waktu(design) > 0;

    inner.push(out);
    // Tanpa proses sekuensial, parameter `clock` tak terpakai; diganti
    // garis bawah agar hasil generate bebas warning `unused_variables`.
    // Pada mode edge nyata juga tak terpakai karena syaratnya tidak
    // merujuk argumen clock.
    let arg_clock = if sequential.is_empty() || edge_nyata {
        "_clock"
    } else {
        "clock"
    };
    out.push_str(&format!(
        "pub fn eval_seq(&mut self, {}: usize) {{\n",
        arg_clock
    ));
    let body = inner.child();
    for process in &sequential {
        let clock_id = process.sensitivity.first().map(|s| s.signal).unwrap_or(0);
        body.push(out);
        out.push_str(&format!("// {} (clock = {})\n", process.name, clock_id));
        body.push(out);
        let events: Vec<sv_ir::process::EventItem> = process
            .sensitivity
            .iter()
            .map(|s| sv_ir::process::EventItem {
                edge: s.edge,
                signal: s.signal,
            })
            .collect();
        // LRM §9.7: selain evaluasi langkah utama pada clock pertama, proses
        // dengan event gabungan (mis. async reset) juga dievaluasi saat edge
        // nyata terjadi pada salah satu sinyal sensitivitasnya.
        let syarat = if edge_nyata {
            edge_test(&events)
        } else if process.sensitivity.len() > 1 {
            format!("clock == {} || ({})", clock_id, edge_test(&events))
        } else {
            format!("clock == {}", clock_id)
        };
        out.push_str(&format!("if {} {{\n", syarat));
        body.push(out);
        write_statements(&process.body, out, &body.child());
        body.push(out);
        out.push_str("}\n");
    }
    inner.push(out);
    out.push_str("}\n\n");
}

/// True bila design butuh field `edge_prev` dan method `sample_edge`.
///
/// Pemicu: menunggu edge di blok `initial`, proses sekuensial dengan event
/// control gabungan (LRM §9.7), atau adanya proses waktu `always #N`
/// (LRM §11.2) — pada kasus terakhir edge clock nyata hanya bisa dikenali
/// lewat perbandingan dengan nilai langkah sebelumnya.
pub fn perlu_edge_prev(design: &Design) -> bool {
    crate::initial_step::total_tunggu(design) > 0
        || ada_event_gabungan(design)
        || crate::time_scan::jumlah_proses_waktu(design) > 0
}

/// True bila ada proses sekuensial dengan lebih dari satu item sensitivitas.
fn ada_event_gabungan(design: &Design) -> bool {
    design
        .processes
        .iter()
        .filter(|p| p.kind == ProcessKind::Sequential)
        .any(|p| p.sensitivity.len() > 1)
}

/// Tulis method `sample_edge` bila design menyimpan `edge_prev`.
///
/// LRM §9.7: nilai sekarang dibandingkan dengan nilai langkah sebelumnya
/// untuk mengenali posedge/negedge, jadi tiap sinyal yang diawasi harus
/// disampel di akhir setiap langkah.
fn write_sample_edge(design: &Design, inner: &Indent, out: &mut String) {
    if !perlu_edge_prev(design) {
        return;
    }
    inner.push(out);
    out.push_str("/// Remember the watched signal values at the end of this step.\n");
    out.push_str("pub fn sample_edge(&mut self) {\n");
    let sample_body = inner.child();
    for sinyal in sinyal_disampel(design) {
        sample_body.push(out);
        out.push_str(&format!(
            "    self.edge_prev[{}] = self.signals[{}].read().to_u64() & 1;\n",
            sinyal, sinyal
        ));
    }
    inner.push(out);
    out.push_str("}\n\n");
}

