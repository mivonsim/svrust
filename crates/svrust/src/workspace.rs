// Tanggung jawab: manage direktori keluaran target/sv dan proyek simulasi paralel per modul root.
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::thread;

use sv_codegen_rust::{generate_module, to_module_name};
use sv_ir::Design;

/// Lokasi crate sv-runtime di workspace (path dependency agar tidak duplikasi).
fn runtime_path() -> Result<PathBuf, String> {
    let cwd = env::current_dir().map_err(|e| e.to_string())?;
    Ok(cwd.join("crates").join("sv-runtime"))
}

/// Lokasi crate sv-trace di workspace (hanya dibutuhkan saat merekam VCD).
fn trace_path() -> Result<PathBuf, String> {
    let cwd = env::current_dir().map_err(|e| e.to_string())?;
    Ok(cwd.join("crates").join("sv-trace"))
}

pub struct Workspace {
    target_sv: PathBuf,
    sim_dir: PathBuf,
}

impl Workspace {
    pub fn detect() -> Result<Self, String> {
        let cwd = env::current_dir().map_err(|e| e.to_string())?;
        let target_sv = cwd.join("target").join("sv");
        let sim_dir = env::temp_dir().join("sv-sim");
        Ok(Self { target_sv, sim_dir })
    }

    pub fn generated_dir(&self) -> PathBuf {
        self.target_sv.join("generated")
    }

    /// Direktori proyek simulasi paralel: satu crate per modul root.
    pub fn parallel_dir(&self) -> PathBuf {
        self.target_sv.join("parallel")
    }

    pub fn sim_project_dir(&self) -> PathBuf {
        self.sim_dir.clone()
    }

    pub fn ensure_dirs(&self) -> Result<(), String> {
        fs::create_dir_all(self.generated_dir()).map_err(|e| e.to_string())?;
        fs::create_dir_all(&self.sim_dir).map_err(|e| e.to_string())?;
        Ok(())
    }

    pub fn write_generated(&self, design_name: &str, rust_code: &str) -> Result<PathBuf, String> {
        self.ensure_dirs()?;
        let mod_name = to_module_name(design_name);
        let path = self.generated_dir().join(mod_name).with_extension("rs");
        fs::write(&path, rust_code).map_err(|e| e.to_string())?;
        Ok(path)
    }

    /// Tulis proyek simulasi paralel: satu crate Cargo per modul root di
    /// `target/sv/parallel/units/<nama>/`, masing-masing binary mandiri yang
    /// dapat dikompilasi secara paralel dengan `cargo -j N`.
    ///
    /// Setiap unit crate berisi:
    ///   - `Cargo.toml`  : dependensi `sv-runtime` (+ `sv-trace` bila VCD)
    ///   - `src/main.rs` : kode modul desain (dibungkus `mod`) + driver simulasi
    ///
    /// Root `parallel/Cargo.toml` adalah workspace yang mencakup semua unit,
    /// sehingga rustc meng-kompilasi setiap modul root dalam crate terpisah
    /// dan linker hanya menangani simbol per unit, bukan satu binary monolitik
    /// dengan ribuan modul (bottleneck utama menurut paralel.md).
    pub fn write_sim_project(
        &self,
        units: &[(&str, &Design, Option<&Path>)],
        steps: usize,
        pakai_vcd: bool,
    ) -> Result<PathBuf, String> {
        let parallel_dir = self.parallel_dir();
        let units_dir = parallel_dir.join("units");
        fs::create_dir_all(&units_dir).map_err(|e| e.to_string())?;

        let runtime_path = runtime_path()?;
        let trace_path = trace_path()?;

        // Header yang disisipkan ke setiap src/main.rs unit.
        let header = "// Generated by cargo-sv. Jangan edit manual.\n\
            #![allow(unused_parens, unused_imports, non_snake_case)]\n\n";

        let mut member_names = Vec::with_capacity(units.len());

        for (module_name, design, vcd_path) in units {
            member_names.push(module_name.to_string());

            let unit_dir = units_dir.join(module_name);
            let src_dir = unit_dir.join("src");
            fs::create_dir_all(&src_dir).map_err(|e| e.to_string())?;

            // Cargo.toml per unit: satu crate binary per modul root.
            let mut unit_cargo = format!(
                "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
                 [[bin]]\nname = \"{}\"\npath = \"src/main.rs\"\n\n\
                 [dependencies]\n\
                 sv-runtime = {{ path = \"{}\" }}\n",
                module_name,
                module_name,
                // Dari parallel/units/<nama>/ ke crates/sv-runtime: ../../../
                runtime_path.display()
            );
            if pakai_vcd && vcd_path.is_some() {
                unit_cargo.push_str(&format!(
                    "sv-trace = {{ path = \"{}\" }}\n",
                    trace_path.display()
                ));
            }
            fs::write(unit_dir.join("Cargo.toml"), unit_cargo).map_err(|e| e.to_string())?;

            // Kode modul desain (generate_module) + driver simulasi per design.
            let rust_code = generate_module(design);
            let driver_code = crate::driver_gen::generate_driver(design, steps, *vcd_path);

            let mut main_content = String::from(header);
            // `Bits` dibutuhkan driver untuk set input / cetak output.
            main_content.push_str("use ::sv_runtime::Bits;\n\n");
            // Setiap design dibungkus `mod` sendiri agar `MAX_WIDTH` dan `use`
            // yang sama tidak bentrok antar unit.
            main_content.push_str(&format!("mod {module_name} {{\n"));
            main_content.push_str(&rust_code);
            main_content.push_str("\n}\n\n");
            main_content.push_str(&driver_code);

            fs::write(src_dir.join("main.rs"), main_content).map_err(|e| e.to_string())?;
        }

        // Root workspace Cargo.toml: satu member per unit crate.
        let mut workspace_cargo = String::from("[workspace]\nresolver = \"2\"\n\nmembers = [\n");
        for m in &member_names {
            workspace_cargo.push_str(&format!("    \"units/{}\",\n", m));
        }
        workspace_cargo.push_str("]\n");

        fs::write(parallel_dir.join("Cargo.toml"), workspace_cargo).map_err(|e| e.to_string())?;

        Ok(parallel_dir.join("Cargo.toml"))
    }

    /// Kompilasi semua unit crate secara paralel (`cargo -j N`) agar ribuan
    /// modul root tidak menangguhkan satu sama lain dalam satu crate monolitik.
    pub fn build(&self, release: bool) -> Result<(), String> {
        let parallel_dir = self.parallel_dir();
        let n = thread::available_parallelism()
            .map(|n| n.get())
            .unwrap_or(1);
        let mut cmd = Command::new("cargo");
        cmd.arg("build");
        if release {
            cmd.arg("--release");
        }
        cmd.arg("-j").arg(n.to_string());
        cmd.current_dir(&parallel_dir);
        let status = cmd
            .status()
            .map_err(|e| format!("gagal jalankan cargo: {}", e))?;
        if !status.success() {
            return Err("cargo build gagal".to_string());
        }
        Ok(())
    }

    /// Jalankan setiap biner unit secara berurutan (simulasi per root).
    /// Plusarg dikirim ke setiap biner.
    pub fn run(
        &self,
        release: bool,
        plusargs: &[(String, String)],
        units: &[(&str, &Design, Option<&Path>)],
    ) -> Result<(), String> {
        let parallel_dir = self.parallel_dir();
        let profile = if release { "release" } else { "debug" };
        let mut gagal = String::new();

        for (module_name, ..) in units {
            let binary = parallel_dir.join("target").join(profile).join(module_name);
            if !binary.exists() {
                gagal.push_str(&format!("biner tidak ditemukan: {}\n", binary.display()));
                continue;
            }
            let mut cmd = Command::new(&binary);
            for (nama, nilai) in plusargs {
                cmd.arg(format!("+{nama}={nilai}"));
            }
            let status = cmd
                .status()
                .map_err(|e| format!("gagal jalankan biner {}: {}", module_name, e))?;
            if !status.success() {
                gagal.push_str(&format!(
                    "biner {} gagal (exit code non-nol)\n",
                    module_name
                ));
            }
        }

        if !gagal.is_empty() {
            return Err(gagal);
        }
        Ok(())
    }

    pub fn clean(&self) -> Result<(), String> {
        if self.target_sv.exists() {
            fs::remove_dir_all(&self.target_sv).map_err(|e| e.to_string())?;
        }
        if self.sim_dir.exists() {
            fs::remove_dir_all(&self.sim_dir).map_err(|e| e.to_string())?;
        }
        // Also clean workspace temp dirs
        let ws_root = env::temp_dir().join("sv-workspace");
        if ws_root.exists() {
            fs::remove_dir_all(&ws_root).map_err(|e| e.to_string())?;
        }
        let gen_temp = env::temp_dir().join("sv-generated-temp");
        if gen_temp.exists() {
            fs::remove_dir_all(&gen_temp).map_err(|e| e.to_string())?;
        }
        Ok(())
    }
}
